import type { Plugin, ResolvedConfig } from 'vite';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { GAME } from '../src/config/game.ts';

/**
 * Offline-first PWA without third-party plugins.
 * - injects title/meta from src/config/game.ts into index.html
 * - emits manifest.webmanifest
 * - writes sw.js that precaches EVERY built file; cache name = content hash, so a new
 *   deploy installs a fresh cache and deletes the old one.
 * Relative URLs everywhere → works under any GitHub Pages sub-path.
 */
export function offlinePwa(): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'tlf-offline-pwa',
    configResolved(c) { config = c; },
    transformIndexHtml: (html) => html
      .replaceAll('%GAME_TITLE%', GAME.title)
      .replaceAll('%GAME_DESCRIPTION%', GAME.description)
      .replaceAll('%THEME_COLOR%', GAME.themeColor),
    generateBundle() {
      this.emitFile({
        type: 'asset', fileName: 'manifest.webmanifest', source: JSON.stringify({
          name: GAME.title, short_name: GAME.shortTitle, description: GAME.description,
          start_url: './', scope: './', display: 'fullscreen', orientation: 'landscape',
          background_color: GAME.backgroundColor, theme_color: GAME.themeColor,
          icons: [
            { src: 'icons/icon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' },
            { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png' },
            { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png' },
          ],
        }, null, 2),
      });
    },
    closeBundle() {
      if (config.command !== 'build') return;
      const out = config.build.outDir, files: string[] = [];
      const walk = (d: string) => { for (const n of readdirSync(d)) { const p = join(d, n); if (statSync(p).isDirectory()) walk(p); else files.push(p); } };
      walk(out);
      const hash = createHash('sha256'), urls: string[] = [];
      for (const f of files.sort()) {
        const rel = relative(out, f).split('\\').join('/');
        if (rel === 'sw.js') continue;
        hash.update(rel).update(readFileSync(f)); urls.push(rel);
      }
      const cache = `tlf-${hash.digest('hex').slice(0, 12)}`;
      writeFileSync(join(out, 'sw.js'), SW.replace('__CACHE__', JSON.stringify(cache)).replace('__URLS__', JSON.stringify(['./', ...urls])));
      config.logger.info(`[offline-pwa] sw.js precaches ${urls.length} files (${cache})`);
    },
  };
}

const SW = `/* generated by build/offline-pwa.ts — do not edit */
const CACHE = __CACHE__;
const URLS = __URLS__;
const MATCH = { ignoreSearch: true, ignoreVary: true };   // servers send Vary: Origin; module requests carry Origin
// Install the new cache and take over at once, but DON'T delete older caches here: a page that is
// still running the previous build may need its files. The page asks for a prune once it has booted.
self.addEventListener('install', (e) => e.waitUntil(caches.open(CACHE).then((c) => c.addAll(URLS)).then(() => self.skipWaiting())));
self.addEventListener('activate', (e) => e.waitUntil(self.clients.claim()));
self.addEventListener('message', (e) => {
  if (e.data && e.data.type === 'prune') e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('tlf-') && k !== CACHE).map((k) => caches.delete(k)))));
});
const put = (req, res) => { if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); } return res; };
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  if (req.mode === 'navigate') {
    // HTML: network first (a new deploy is picked up immediately), cache when offline
    e.respondWith(fetch(req).then((res) => put(req, res)).catch(() => caches.match(req, MATCH).then((hit) => hit || caches.match('index.html', MATCH))));
    return;
  }
  // hashed assets: any cache (current or previous build), then network
  e.respondWith(caches.match(req, MATCH).then((hit) => hit || fetch(req).then((res) => put(req, res))).catch(() => Response.error()));
});
`;
