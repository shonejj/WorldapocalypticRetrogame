import type { Plugin, ResolvedConfig } from 'vite';
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { GAME } from '../src/config/game.ts';

/**
 * Offline-first support without third-party plugins:
 *  - injects the game title/meta from src/config/game.ts into index.html
 *  - emits manifest.webmanifest
 *  - after the bundle is written, emits sw.js that precaches EVERY file in dist
 *    (cache name = hash of all file contents, so each deploy updates cleanly)
 * All URLs are relative, so the build works under any GitHub Pages sub-path.
 */
export function offlinePwa(): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'tlf-offline-pwa',
    configResolved(c) { config = c; },
    transformIndexHtml(html) {
      return html
        .replaceAll('%GAME_TITLE%', GAME.title)
        .replaceAll('%GAME_DESCRIPTION%', GAME.description)
        .replaceAll('%THEME_COLOR%', GAME.themeColor);
    },
    generateBundle() {
      const manifest = {
        name: GAME.title,
        short_name: GAME.shortTitle,
        description: GAME.description,
        start_url: './',
        scope: './',
        display: 'fullscreen',
        orientation: 'landscape',
        background_color: GAME.backgroundColor,
        theme_color: GAME.themeColor,
        icons: [
          { src: 'icons/icon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' },
          { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png' },
          { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png' },
        ],
      };
      this.emitFile({ type: 'asset', fileName: 'manifest.webmanifest', source: JSON.stringify(manifest, null, 2) });
    },
    closeBundle() {
      if (config.command !== 'build') return;
      const outDir = config.build.outDir;
      const files: string[] = [];
      const walk = (dir: string) => {
        for (const name of readdirSync(dir)) {
          const p = join(dir, name);
          if (statSync(p).isDirectory()) walk(p);
          else files.push(p);
        }
      };
      walk(outDir);
      const hash = createHash('sha256');
      const urls: string[] = [];
      for (const f of files.sort()) {
        const rel = relative(outDir, f).split('\\').join('/');
        if (rel === 'sw.js') continue;
        hash.update(rel).update(readFileSync(f));
        urls.push(rel);
      }
      const version = hash.digest('hex').slice(0, 12);
      const sw = SW_TEMPLATE
        .replace('__CACHE__', JSON.stringify(`tlf-${version}`))
        .replace('__URLS__', JSON.stringify(['./', ...urls.filter((u) => u !== 'index.html'), 'index.html']));
      writeFileSync(join(outDir, 'sw.js'), sw);
      config.logger.info(`[offline-pwa] sw.js precaches ${urls.length} files (cache tlf-${version})`);
    },
  };
}

const SW_TEMPLATE = `/* generated by build/pwa-plugin.ts */
const CACHE = __CACHE__;
const URLS = __URLS__;
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(URLS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('tlf-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(
    caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
      return res;
    }).catch(() => req.mode === 'navigate' ? caches.match('index.html', { ignoreVary: true }) : Response.error()))
  );
});
`;
